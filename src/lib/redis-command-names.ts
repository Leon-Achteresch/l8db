export function redisCommandMatches(line: string): string[] {
  const match = /^\s*([A-Za-z]*)$/.exec(line);
  if (!match) return [];
  const prefix = match[1].toUpperCase();
  return REDIS_COMMAND_NAMES.filter((name) => name.startsWith(prefix));
}
